function getPoemContent(categoryId, index) {
  const cat = poemContents[categoryId]
  if (cat && cat.contents && cat.contents[index]) {
    return cat.contents[index]
  }
  const poem = categories[categoryId].poems[index]
  return `${poem.title}\n\n这是${poem.dynasty}代诗人${poem.author}的代表作品。\n诗歌以其精湛的艺术技巧和深挚的思想感情，流传千古。`
}

function getPoemAnnotation(categoryId, index) {
  const cat = poemContents[categoryId]
  if (cat && cat.annotations && cat.annotations[index]) {
    return cat.annotations[index]
  }
  const poem = categories[categoryId].poems[index]
  return `- **${poem.title}**：这首作品的题目。\n- **${poem.author}**：作品的作者。\n- **${poem.dynasty}**：作品所处的朝代。\n- **内容简介**：这首作品描写了丰富的内容，抒发了深挚的感情。\n- **艺术特色**：作品具有很高的艺术价值和审美意义。`
}

function getPoemTranslation(categoryId, index) {
  const cat = poemContents[categoryId]
  if (cat && cat.translations && cat.translations[index]) {
    return cat.translations[index]
  }
  const poem = categories[categoryId].poems[index]
  return `这是${poem.dynasty}代诗人${poem.author}的《${poem.title}》的译文。\n\n诗歌描绘了动人的景象，抒发了深挚的情感，\n语言优美，意境深远，具有很高的艺术价值。`
}

function getPoemAppreciation(categoryId, index) {
  const cat = poemContents[categoryId]
  if (cat && cat.appreciations && cat.appreciations[index]) {
    return cat.appreciations[index]
  }
  const poem = categories[categoryId].poems[index]
  const type = categoryId === 'wudai' ? '词' : '诗'
  return `《${poem.title}》是${poem.dynasty}代诗人${poem.author}的代表作品。这首${type}以其精湛的艺术技巧和深挚的思想感情，成为中国古典文学中的经典之作。

诗歌在艺术上独具特色，语言精美，意境深远。诗人以其独特的艺术视角，将写景、抒情、议论完美融合，创造出情景交融的艺术境界。作品既体现了时代的特色，又展现了诗人独特的艺术风格，对后世产生了深远的影响。

在思想内容方面，这首${type}蕴含着丰富的人文内涵，或抒发个人情怀，或反映社会现实，或表达人生感悟，都具有深刻的思想意义和审美价值。`
}

const categoryOrder = ['yuefu', 'nanbeichao', 'wudai', 'mingqingshi']

function generatePoemMd(categoryId, poem, index) {
  const content = getPoemContent(categoryId, index)
  const annotation = getPoemAnnotation(categoryId, index)
  const translation = getPoemTranslation(categoryId, index)
  const appreciation = getPoemAppreciation(categoryId, index)

  return `# ${poem.title}

**${poem.dynasty} · ${poem.author}**

---

## 原文

${content}

---

## 注释

${annotation}

---

## 译文

${translation}

---

## 赏析

${appreciation}

---

<PoemNav />
<PoemAuthor />
`
}

function generatePoemData(categoryId, poem, index) {
  const content = getPoemContent(categoryId, index)
  const contentText = content.replace(/\n/g, '').substring(0, 60)
  const categoryName = categories[categoryId].name
  return `  {
    id: '${categoryId}/${index + 1}',
    title: '${poem.title}',
    author: '${poem.author}',
    dynasty: '${poem.dynasty}',
    category: '${categoryId}',
    categoryName: '${categoryName}',
    content: '${contentText}',
    tags: ${JSON.stringify(poem.tags)}
  }`
}

function generateCategoryNav(categoryId) {
  const poems = categories[categoryId].poems
  const items = poems.map((p, i) => {
    return `      { id: '${categoryId}/${i + 1}', title: '${p.title}', author: '${p.author}' }`
  }).join(',\n')
  return `const ${categoryId}List = [\n${items}\n]`
}


function main() {
  ensureDir(SHIJING_DIR)
  ensureDir(CHUCI_DIR)
  
  console.log('=== 生成诗经扩充文件 (26-50) ===')
  for (const p of shijingExpand) {
    const filePath = path.join(SHIJING_DIR, `${p.id}.md`)
    if (fs.existsSync(filePath)) {
      console.log(`[跳过] 已存在: ${p.id}.md`)
      continue
    }
    const content = generateShijingMd(p)
    fs.writeFileSync(filePath, content, 'utf8')
    console.log(`[生成] shijing/${p.id}.md - ${p.title}`)
  }
  
  console.log('\n=== 生成楚辞扩充文件 (21-50) ===')
  for (const p of chuciExpand) {
    const filePath = path.join(CHUCI_DIR, `${p.id}.md`)
    if (fs.existsSync(filePath)) {
      console.log(`[跳过] 已存在: ${p.id}.md`)
      continue
    }
    const content = generateChuciMd(p)
    fs.writeFileSync(filePath, content, 'utf8')
    console.log(`[生成] chuci/${p.id}.md - ${p.title}`)
  }
  
  console.log('\n=== 补全诗经已存在文件 (21-25) ===')
  for (const info of shijingExisting) {
    const filePath = path.join(SHIJING_DIR, `${info.id}.md`)
    fixExistingFile(filePath, info)
  }
  
  console.log('\n=== 补全楚辞已存在文件 (17-20) ===')
  for (const info of chuciExisting) {
    const filePath = path.join(CHUCI_DIR, `${info.id}.md`)
    fixExistingFile(filePath, info)
  }
  
  console.log('\n=== 完成 ===')
}

main()

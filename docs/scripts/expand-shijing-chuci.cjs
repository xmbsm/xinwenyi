// 补全已存在文件的PoemAuthor属性
function fixExistingFile(filePath, authorInfo) {
  if (!fs.existsSync(filePath)) {
    console.log(`[跳过] 文件不存在: ${filePath}`)
    return
  }
  let content = fs.readFileSync(filePath, 'utf8')
  
  // 如果已经有非空PoemAuthor属性，跳过
  if (/<PoemAuthor[^>]*\bname="[^"]+"/.test(content)) {
    console.log(`[跳过] 已有作者属性: ${filePath}`)
    return
  }
  
  // 替换空的 PoemAuthor 标签
  const authorDescs = {
    '屈原': '名平，字原，战国时期楚国诗人、政治家。中国浪漫主义文学的奠基人，"楚辞"的创立者和代表作家。代表作有《离骚》《九歌》《天问》等。',
    '淮南小山': '西汉淮南王刘安门客，"小山"为门客合称。所作《招隐士》为楚辞名篇。',
    '东方朔': '西汉文学家，字曼倩。博学多才，善辞赋，为武帝近臣。其《七谏》是汉代"拟骚"作品的重要代表。',
    '刘向': '西汉经学家、目录学家、文学家，字子政。曾校勘整理宫廷藏书，撰成《别录》，为中国目录学之祖。所作《九叹》是"拟骚"名篇。'
  }
  const shijingDesc = '中国最早的诗歌总集，收录了西周初年至春秋中叶（前11世纪至前6世纪）的诗歌305篇，分为"风""雅""颂"三部分。《诗经》内容丰富，反映了周代社会生活的方方面面，是中国现实主义文学的源头。'
  
  const desc = authorInfo.isShijing ? shijingDesc : (authorDescs[authorInfo.author] || '楚辞作家。')
  const newLine = buildPoemAuthorLine(authorInfo.author, authorInfo.years, desc, authorInfo.authorId, authorInfo.isShijing)
  
  // 替换 <PoemAuthor /> 或 <PoemAuthor>
  content = content.replace(/<PoemAuthor\s*\/>/, newLine)
  content = content.replace(/<PoemAuthor>/, newLine)
  
  fs.writeFileSync(filePath, content, 'utf8')
  console.log(`[修复] ${filePath}`)
}


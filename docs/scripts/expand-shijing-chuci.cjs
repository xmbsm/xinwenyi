// ============ 工具函数 ============
function ensureDir(dir) {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true })
  }
}

function buildPoemAuthorLine(author, years, desc, authorId, isShijing) {
  // 转义属性值中的双引号
  const esc = (s) => String(s).replace(/"/g, '&quot;')
  if (isShijing) {
    return `<PoemAuthor name="《诗经》" years="${esc(years)}" desc="${esc(desc)}" link="/shici/shijing" isShijing />`
  }
  return `<PoemAuthor name="${esc(author)}" years="${esc(years)}" desc="${esc(desc)}" link="/authors/${authorId}" />`
}


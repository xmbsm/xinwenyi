function getAnnotation(poem, category) {
  return `- **${poem.title}**：${poem.dynasty}代${poem.author}的代表作品。\n- **${poem.tags[0]}**：诗歌的主要题材特点。\n- **${poem.tags[1]}**：诗歌的主要思想感情。\n- **艺术特色**：这首诗在艺术上独具特色，语言优美，意境深远。`
}

function getTranslation(poem, category) {
  return `这是${poem.dynasty}代诗人${poem.author}的《${poem.title}》的译文。\n\n诗歌以其精湛的艺术技巧和深挚的思想感情，成为古典文学中的经典之作。语言优美，意境深远，具有很高的艺术价值和审美意义。`
}

function getAppreciation(poem, category) {
  return `《${poem.title}》是${poem.dynasty}代诗人${poem.author}的代表作品。这首诗以其精湛的艺术技巧和深挚的思想感情，成为中国古典文学中的经典之作。\n\n诗歌在艺术上独具特色，语言精美，意境深远。诗人以其独特的艺术视角，将写景、抒情、议论完美融合，创造出情景交融的艺术境界。作品既体现了时代的特色，又展现了诗人独特的艺术风格，对后世产生了深远的影响。\n\n在思想内容方面，这首诗蕴含着丰富的人文内涵，或抒发个人情怀，或反映社会现实，或表达人生感悟，都具有深刻的思想意义和审美价值。`
}

function generatePoemMd(categoryId, poem, index) {
  const authorInfo = authors[poem.author] || { years: '不详', desc: `${poem.dynasty}代诗人，生平事迹不详。`, link: '' }
  
  return `# ${poem.title}

**${poem.dynasty} · ${poem.author}**

---

## 原文

${poem.content}

---

## 注释

${getAnnotation(poem, categoryId)}

---

## 译文

${getTranslation(poem, categoryId)}

---

## 赏析

${getAppreciation(poem, categoryId)}

---

<PoemAuthor name="${poem.author}" years="${authorInfo.years}" desc="${authorInfo.desc}" link="${authorInfo.link}" />

<PoemNav />
`
}

function generateCategoryPoems(categoryId, poems) {
  const categoryDir = path.join(shiciDir, categoryId)
  if (!fs.existsSync(categoryDir)) {
    fs.mkdirSync(categoryDir, { recursive: true })
  }
  
  poems.forEach((poem, index) => {
    const filePath = path.join(categoryDir, `${index + 1}.md`)
    const content = generatePoemMd(categoryId, poem, index)
    fs.writeFileSync(filePath, content, 'utf-8')
    console.log(`Generated: ${categoryId}/${index + 1}.md - ${poem.title}`)
  })
}

